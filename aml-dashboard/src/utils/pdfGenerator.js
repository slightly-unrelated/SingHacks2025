import jsPDF from 'jspdf';

export const generateTransactionReport = (transaction) => {
  const doc = new jsPDF();

  // Header
  doc.setFontSize(20);
  doc.setTextColor(27, 43, 61); // primary-navy
  doc.text('Julius Bär - AML Transaction Report', 20, 20);

  // Transaction ID
  doc.setFontSize(10);
  doc.setTextColor(100, 100, 100);
  doc.text(`Transaction ID: ${transaction.id}`, 20, 30);

  // Divider
  doc.setDrawColor(200, 200, 200);
  doc.line(20, 35, 190, 35);

  // Risk Score Section
  doc.setFontSize(16);
  doc.setTextColor(27, 43, 61);
  doc.text('Risk Assessment', 20, 45);

  doc.setFontSize(12);
  doc.text(`Risk Score: ${transaction.riskScore}/100`, 20, 55);
  doc.text(`Risk Level: ${transaction.riskRating}`, 20, 62);

  if (transaction.flagReason) {
    doc.setFontSize(10);
    doc.setTextColor(163, 0, 0); // risk-high
    doc.text('⚠ Red Flag:', 20, 72);
    doc.setTextColor(51, 51, 51);
    const splitText = doc.splitTextToSize(transaction.flagReason, 170);
    doc.text(splitText, 20, 79);
  }

  // Customer Information
  let yPos = transaction.flagReason ? 95 : 75;
  doc.setFontSize(16);
  doc.setTextColor(27, 43, 61);
  doc.text('Customer Information', 20, yPos);

  yPos += 10;
  doc.setFontSize(11);
  doc.setTextColor(51, 51, 51);
  doc.text(`Name: ${transaction.customerName}`, 20, yPos);
  doc.text(`Customer ID: ${transaction.customerId}`, 20, yPos + 7);
  doc.text(`PEP Status: ${transaction.isPep ? 'Yes ⚠' : 'No'}`, 20, yPos + 14);

  // Transaction Details
  yPos += 25;
  doc.setFontSize(16);
  doc.setTextColor(27, 43, 61);
  doc.text('Transaction Details', 20, yPos);

  yPos += 10;
  doc.setFontSize(11);
  doc.setTextColor(51, 51, 51);
  doc.text(`Amount: ${transaction.currency} ${transaction.amount.toLocaleString()}`, 20, yPos);
  doc.text(`Date: ${new Date(transaction.date).toLocaleString()}`, 20, yPos + 7);
  doc.text(`Jurisdiction: ${transaction.jurisdiction}`, 20, yPos + 14);
  doc.text(`Product Type: ${transaction.productType.replace('_', ' ')}`, 20, yPos + 21);
  doc.text(`Sanctions Screening: ${transaction.sanctionsScreening}`, 20, yPos + 28);

  // Compliance Checks
  yPos += 40;
  doc.setFontSize(16);
  doc.setTextColor(27, 43, 61);
  doc.text('Compliance Status', 20, yPos);

  yPos += 10;
  doc.setFontSize(11);
  const eddStatus = transaction.eddRequired
    ? transaction.eddPerformed
      ? '✓ Complete'
      : '✗ Required but not performed'
    : 'Not Required';
  doc.text(`Enhanced Due Diligence: ${eddStatus}`, 20, yPos);

  const strStatus = transaction.strFiled
    ? `✓ Filed ${transaction.strFiledDate ? `on ${new Date(transaction.strFiledDate).toLocaleDateString()}` : ''}`
    : 'Not Filed';
  doc.text(`Suspicious Transaction Report: ${strStatus}`, 20, yPos + 7);

  // Footer
  doc.setFontSize(8);
  doc.setTextColor(150, 150, 150);
  doc.text('Generated by Julius Bär AML Monitor', 20, 280);
  doc.text(`Report Date: ${new Date().toLocaleString()}`, 20, 285);

  // Save
  doc.save(`Transaction_Report_${transaction.id.substring(0, 8)}.pdf`);
};

export const generateDocumentReport = (document) => {
  const doc = new jsPDF();

  // Header
  doc.setFontSize(20);
  doc.setTextColor(27, 43, 61);
  doc.text('Julius Bär - Document Analysis Report', 20, 20);

  doc.setFontSize(10);
  doc.setTextColor(100, 100, 100);
  doc.text(`Document: ${document.fileName}`, 20, 30);

  // Divider
  doc.setDrawColor(200, 200, 200);
  doc.line(20, 35, 190, 35);

  // Risk Score
  doc.setFontSize(16);
  doc.setTextColor(27, 43, 61);
  doc.text('Risk Assessment', 20, 45);

  doc.setFontSize(12);
  doc.text(`Risk Score: ${document.riskScore}/100`, 20, 55);
  doc.text(`Status: ${document.status === 'approved' ? 'Approved ✓' : 'Flagged ⚠'}`, 20, 62);

  // Extracted Data
  let yPos = 75;
  doc.setFontSize(16);
  doc.setTextColor(27, 43, 61);
  doc.text('Extracted Data', 20, yPos);

  yPos += 10;
  doc.setFontSize(11);
  doc.setTextColor(51, 51, 51);
  Object.entries(document.extractedData).forEach(([key, value]) => {
    doc.text(`${key.replace(/([A-Z])/g, ' $1').trim()}: ${value}`, 20, yPos);
    yPos += 7;
  });

  // Issues Found
  yPos += 5;
  doc.setFontSize(16);
  doc.setTextColor(27, 43, 61);
  doc.text(`Issues Found (${document.issues.length})`, 20, yPos);

  yPos += 10;
  document.issues.forEach((issue, index) => {
    doc.setFontSize(11);

    // Set color based on issue type
    if (issue.type === 'critical') {
      doc.setTextColor(163, 0, 0);
      doc.text(`✗ CRITICAL:`, 20, yPos);
    } else if (issue.type === 'warning') {
      doc.setTextColor(255, 165, 0);
      doc.text(`⚠ WARNING:`, 20, yPos);
    } else {
      doc.setTextColor(40, 167, 69);
      doc.text(`✓ PASS:`, 20, yPos);
    }

    doc.setTextColor(51, 51, 51);
    const splitText = doc.splitTextToSize(issue.message, 160);
    doc.text(splitText, 45, yPos);
    yPos += 7 * splitText.length + 3;
  });

  // Footer
  doc.setFontSize(8);
  doc.setTextColor(150, 150, 150);
  doc.text('Generated by Julius Bär AML Monitor', 20, 280);
  doc.text(`Report Date: ${new Date().toLocaleString()}`, 20, 285);

  // Save
  doc.save(`Document_Report_${document.id}.pdf`);
};
